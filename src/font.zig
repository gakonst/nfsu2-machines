comptime {
    std.debug.assert(glyphs.len == LAST - FIRST + 1);
}

/// Rows of the glyph for c; unknown characters draw as '?'.
pub fn glyph(c: u8) *const [7]u8 {
    var k = c;
    if (k >= 'a' and k <= 'z') k -= 32;
    if (k < FIRST or k > LAST) k = '?';
    return &glyphs[k - FIRST];
}

/// Width in pixels of str at the given scale (no trailing gap).
pub fn measure(str: []const u8, scale: u32) u32 {
    if (str.len == 0) return 0;
    return @as(u32, @intCast(str.len)) * ADVANCE * scale - scale;
}

/// Draws str at (x, y) (top left) in rgba (0xRRGGBBAA; alpha blends). Clipped to the frame.
pub fn text(fb: []u8, w: u32, h: u32, x: i32, y: i32, str: []const u8, rgba: u32) void {
    textScaled(fb, w, h, x, y, str, rgba, 1);
}

/// Like text, each font pixel drawn as a scale x scale block.
pub fn textScaled(fb: []u8, w: u32, h: u32, x: i32, y: i32, str: []const u8, rgba: u32, scale: u32) void {
    std.debug.assert(fb.len >= @as(usize, w) * h * 4);
    std.debug.assert(scale >= 1 and scale <= 64);
    const max_chars: usize = 256;
    const n = @min(str.len, max_chars);
    const s: i32 = @intCast(scale);
    var ci: usize = 0;
    while (ci < n) : (ci += 1) {
        const g = glyph(str[ci]);
        const gx = x + @as(i32, @intCast(ci)) * @as(i32, ADVANCE) * s;
        if (gx >= @as(i32, @intCast(w))) break;
        var row: u32 = 0;
        while (row < GLYPH_H) : (row += 1) {
            const bits = g[row];
            var col: u32 = 0;
            while (col < GLYPH_W) : (col += 1) {
                if (bits & (@as(u8, 0x10) >> @intCast(col)) == 0) continue;
                block(fb, w, h, gx + @as(i32, @intCast(col)) * s, y + @as(i32, @intCast(row)) * s, s, rgba);
            }
        }
    }
}

fn block(fb: []u8, w: u32, h: u32, x0: i32, y0: i32, s: i32, rgba: u32) void {
    const r: u32 = (rgba >> 24) & 0xff;
    const g: u32 = (rgba >> 16) & 0xff;
    const b: u32 = (rgba >> 8) & 0xff;
    const a: u32 = rgba & 0xff;
    const xa = @max(x0, 0);
    const ya = @max(y0, 0);
    const xb = @min(x0 + s, @as(i32, @intCast(w)));
    const yb = @min(y0 + s, @as(i32, @intCast(h)));
    var yy = ya;
    while (yy < yb) : (yy += 1) {
        var xx = xa;
        while (xx < xb) : (xx += 1) {
            const i = (@as(usize, @intCast(yy)) * w + @as(usize, @intCast(xx))) * 4;
            fb[i] = @intCast((r * a + @as(u32, fb[i]) * (255 - a)) / 255);
            fb[i + 1] = @intCast((g * a + @as(u32, fb[i + 1]) * (255 - a)) / 255);
            fb[i + 2] = @intCast((b * a + @as(u32, fb[i + 2]) * (255 - a)) / 255);
            fb[i + 3] = 255;
        }
    }
}

test "text clips at every edge" {
    var buf: [32 * 16 * 4]u8 = [_]u8{0} ** (32 * 16 * 4);
    text(&buf, 32, 16, -3, -2, "HELLO 24H", 0xffffffff);
    text(&buf, 32, 16, 28, 12, "NITE", 0xff00ffff);
    textScaled(&buf, 32, 16, 1, 1, "Ab?", 0x00ff0080, 3);
    try std.testing.expectEqual(@as(u32, 23), measure("NITE", 1));
    try std.testing.expect(glyph('a') == glyph('A'));
}
