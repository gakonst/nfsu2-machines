// Writes web/worker/src/util/unicode-tables.js from the Rust server's own tables: the general categories that
// nfsu2-names and nfsu2-lan's text.rs read (their unicode-general-category crate's Unicode), dumped by the test-only
// example web/server-rs/crates/names/examples/difftrace_names.rs --tables.  Run: node web/worker/scripts/gen-unicode-tables.mjs
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const serverRs = path.resolve(here, '../../server-rs');
const out = path.resolve(here, '../src/util/unicode-tables.js');

/** the Rust crate's tables: {unassigned, marks, controlFormat}, each [[first, last], ...] */
export function rustTables() {
  const r = spawnSync('cargo', ['run', '--release', '-q', '-p', 'nfsu2-names', '--example', 'difftrace_names', '--', '--tables'],
    { cwd: serverRs, encoding: 'utf8', maxBuffer: 1 << 28 });
  if (r.error || r.status !== 0) throw new Error('cargo failed: ' + (r.error?.message ?? r.stderr));
  return JSON.parse(r.stdout);
}

/** ranges as base-36 gaps and lengths: "gap,len-1,gap,len-1,..." (gap from the end of the range before, plus one) */
export function pack(ranges) {
  const parts = [];
  let next = 0;
  for (const [a, b] of ranges) {
    if (!(a >= next && b >= a)) throw new Error('ranges out of order');
    parts.push((a - next).toString(36), (b - a).toString(36));
    next = b + 1;
  }
  return parts.join(',');
}

/** the module's source for these tables */
export function source(t, crate) {
  return '// Generated by web/worker/scripts/gen-unicode-tables.mjs from the Rust server\'s ' + crate + ' (the general\n' +
    '// categories nfsu2-names and nfsu2-lan text.rs read): do not edit.  web/worker/test/names/unicode-tables.test.mjs\n' +
    '// checks it against the Rust crate.  Ranges of code points as base-36 "gap,length-1" pairs.\n\n' +
    'export const SOURCE = ' + JSON.stringify(crate) + ';\n' +
    'export const UNASSIGNED = ' + JSON.stringify(pack(t.unassigned)) + ';\n' +
    'export const MARKS = ' + JSON.stringify(pack(t.marks)) + ';\n' +
    'export const CONTROL_FORMAT = ' + JSON.stringify(pack(t.controlFormat)) + ';\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const lock = fs.readFileSync(path.join(serverRs, 'Cargo.lock'), 'utf8');
  const v = /name = "unicode-general-category"\nversion = "([^"]+)"/.exec(lock)?.[1] ?? '?';
  fs.writeFileSync(out, source(rustTables(), 'unicode-general-category ' + v));
  console.log('wrote', out);
}

